#!/usr/bin/env node
// Build-time codegen: bakes REGISTRY/ESCROW/deployBlock into src/networks.generated.ts
// from agents/deployments.3961.json (preferred) or agents/deployments.json
// (the name SPEC.md uses), if either exists. Runs as the sdk "prebuild" step.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const agentsRoot = join(__dirname, "..", "..");
const candidates = [
  join(agentsRoot, "deployments.3961.json"),
  join(agentsRoot, "deployments.json"),
];

const ZERO = "0x0000000000000000000000000000000000000000";
let registry = ZERO;
let nft = "0x0000000000000000000000000000000000000000";
let escrow = ZERO;
let deployBlock = 0;
let found = false;
let sourceFile = null;

// Addendum v3 — Agent Economy (SPEC.md "## S."): addresses come from these
// deployments.3961.json keys. Empty string ("" — NOT the zero address) means
// "not deployed yet"; sdk/src/networks.ts + the v3 SDK modules treat "" as
// missing and throw NotDeployed / return {error:"not deployed"} over MCP.
const V3_KEYS = [
  ["x402Vault", "x402Vault"],
  ["accountFactory", "accountFactory"],
  ["accountImpl", "accountImpl"],
  ["streamPay", "streamPay"],
  ["arbiterPool", "arbiterPool"],
  ["identity8004", "identity8004"],
  ["reputation8004", "reputation8004"],
  ["validation8004", "validation8004"],
  ["tokenFactory", "tokenFactory"],
  // The record lane — AI-CV / AI-LinkedIn.
  ["memoryAnchor", "memoryAnchor"],
  ["endorsements", "endorsements"],
];
const v3 = Object.fromEntries(V3_KEYS.map(([, jsonKey]) => [jsonKey, ""]));

for (const path of candidates) {
  if (!existsSync(path)) continue;
  try {
    const j = JSON.parse(readFileSync(path, "utf8"));
    if (j.registry) registry = j.registry;
    if (j.escrow) escrow = j.escrow;
    if (j.nft) nft = j.nft;
    if (typeof j.deployBlock === "number") deployBlock = j.deployBlock;
    for (const [, jsonKey] of V3_KEYS) if (typeof j[jsonKey] === "string" && j[jsonKey]) v3[jsonKey] = j[jsonKey];
    found = true;
    sourceFile = path;
    break;
  } catch (err) {
    console.warn(`[gen-networks] failed to parse ${path}:`, err.message);
  }
}

// The record lane (MemoryAnchor + Endorsements) deploys on its own schedule and
// writes its own file; overlay it so no address has to be set by hand. Matches
// gateway/src/config.ts's CV_DEPLOYMENT_FILES.
for (const name of ["deployments-cv.3961.json", "deployments-cv.json"]) {
  const path = join(agentsRoot, name);
  if (!existsSync(path)) continue;
  try {
    const j = JSON.parse(readFileSync(path, "utf8"));
    for (const [, jsonKey] of V3_KEYS) if (typeof j[jsonKey] === "string" && j[jsonKey]) v3[jsonKey] = j[jsonKey];
    break;
  } catch (err) {
    console.warn(`[gen-networks] failed to parse ${path}:`, err.message);
  }
}

const v3Consts = V3_KEYS.map(
  ([constSuffix, jsonKey]) => `export const GENERATED_${constSuffix.toUpperCase()} = ${JSON.stringify(v3[jsonKey])};`,
).join("\n");

const out = `// AUTO-GENERATED by scripts/gen-networks.mjs at build time. Do not edit by hand.
// Source: ${sourceFile ? sourceFile : "none found — placeholders in effect"}
export const GENERATED_REGISTRY = ${JSON.stringify(registry)};
export const GENERATED_ESCROW = ${JSON.stringify(escrow)};
export const GENERATED_NFT = ${JSON.stringify(nft)};
export const GENERATED_DEPLOY_BLOCK = ${deployBlock};
export const GENERATED_FOUND = ${found};
// Addendum v3 — Agent Economy contract addresses ("" = not deployed yet).
${v3Consts}
`;

writeFileSync(join(__dirname, "..", "src", "networks.generated.ts"), out);
console.log(
  `[gen-networks] wrote src/networks.generated.ts (found=${found}${sourceFile ? ", source=" + sourceFile : ""})`,
);
